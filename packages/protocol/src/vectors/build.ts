export async function buildLive() {
  const phone = id("phone");
  const desktop = id("desktop");
  const sessionId = session("live");
  const ie = eph("live/initiator");
  const re = eph("live/responder");
  const common = { initiatorId: phone.deviceId, responderId: desktop.deviceId, sessionId, maxChunk: 48 };
  const init = new LiveInitiator({ ...common, me: phone.noise, peer: desktop.noise.publicKey, e: ie });
  const m1 = await init.start();
  const { reply: m2, session: dSession } = await liveRespond({ ...common, me: desktop.noise, peer: phone.noise.publicKey, e: re }, m1);
  const pSession = await init.finish(m2);
  const messages: Record<string, unknown>[] = [
    { from: "initiator", kind: "handshake", data: toB64url(m1) },
    { from: "responder", kind: "handshake", data: toB64url(m2) },
  ];
  const rpc = [
    { from: "initiator", msg: { jsonrpc: "2.0", id: 1, method: "hello", params: { protocol_versions: [1] } } },
    { from: "responder", msg: { jsonrpc: "2.0", id: 1, result: { protocol_version: 1 } } },
    { from: "initiator", msg: { jsonrpc: "2.0", id: 2, method: "threads.list", params: {} } },
  ];
  for (const r of rpc) {
    const s = r.from === "initiator" ? pSession : dSession;
    const frames = s.encrypt(r.msg as never);
    messages.push({ from: r.from, kind: "message", frames: frames.map(toB64url), plaintext: JSON.stringify(r.msg) });
  }
  // A first message made for another session id: the responder must refuse it.
  const otherInit = new LiveInitiator({ ...common, sessionId: session("live/other"), me: phone.noise, peer: desktop.noise.publicKey, e: eph("live/other") });
  return {
    $comment: COMMENT("Live sessions (§9.4): Noise_KK, prologue = framed(label, initiator id, responder id, session id); JSON-RPC messages in fragments of at most `max_chunk` bytes here."),
    devices: { initiator: keys("phone"), responder: keys("desktop") },
    session_id: sessionId,
    prologue: toHex(livePrologue(phone.deviceId, desktop.deviceId, sessionId)),
    initiator_ephemeral: toHex(ie.secretKey),
    responder_ephemeral: toHex(re.secretKey),
    max_chunk: 48,
    handshake_hash: toHex(pSession.handshakeHash),
    messages,
    reject: [
      { name: "first message for another session", data: toB64url(await otherInit.start()) },
      { name: "first message with a payload", data: toB64url(await firstWithPayload(phone, desktop, sessionId)) },
    ],
  };
}

function firstWithPayload(phone: ReturnType<typeof id>, desktop: ReturnType<typeof id>, sessionId: string): Promise<Uint8Array> {
  // Built directly on the handshake so the payload rule, not the prologue, is what fails.
  const hs = new HandshakeState({
    pattern: "KK",
    initiator: true,
    prologue: livePrologue(phone.deviceId, desktop.deviceId, sessionId),
    s: phone.noise,
    rs: desktop.noise.publicKey,
    e: eph("live/payload"),
  });
  return hs.writeMessage(utf8('{"jsonrpc":"2.0","id":9,"method":"tasks.run"}'));
}

