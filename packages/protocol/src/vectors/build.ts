function statementBody(o: { platform: "ios" | "web"; method: "qr" | "code"; device: VectorDeviceName }): LinkStatementBody {
  return {
    v: 1,
    account: ACCOUNT,
    desktop_device_id: keys("desktop").device_id,
    device_id: keys(o.device).device_id,
    desktop_static_public_key: keys("desktop").x25519_public,
    device_static_public_key: keys(o.device).x25519_public,
    device_signing_public_key: keys(o.device).ed25519_public,
    platform: o.platform,
    method: o.method,
    created_at: T0,
  };
}

export async function buildStatements() {
  const desktop = id("desktop");
  const body = statementBody({ platform: "ios", method: "qr", device: "phone" });
  const signed = await signLinkStatement(body, desktop.signing);
  const webSigned = await signLinkStatement(statementBody({ platform: "web", method: "code", device: "web" }), desktop.signing);
  const otherSigner = await signLinkStatement(body, id("other").signing);
  return {
    $comment: COMMENT("Link statements (§10.5, §10.7): Ed25519 over `bytes`; `verify` cases give whether the statement verifies against `signer`."),
    devices: { desktop: keys("desktop"), phone: keys("phone"), web: keys("web"), other: keys("other") },
    sign: [
      { name: "ios by QR", body, bytes: toHex(linkStatementBytes(body)), statement: signed },
      { name: "web by code", body: statementBody({ platform: "web", method: "code", device: "web" }), bytes: toHex(linkStatementBytes(statementBody({ platform: "web", method: "code", device: "web" }))), statement: webSigned },
    ],
    verify: [
      { name: "valid", statement: signed, signer: keys("desktop").ed25519_public, valid: true },
      { name: "platform changed", statement: { ...signed, platform: "web" }, signer: keys("desktop").ed25519_public, valid: false },
      { name: "device key changed", statement: { ...signed, device_static_public_key: keys("other").x25519_public }, signer: keys("desktop").ed25519_public, valid: false },
      { name: "account changed", statement: { ...signed, account: "user_someone_else" }, signer: keys("desktop").ed25519_public, valid: false },
      { name: "signed by another device", statement: otherSigner, signer: keys("desktop").ed25519_public, valid: false },
      { name: "extra field", statement: { ...signed, admin: true }, signer: keys("desktop").ed25519_public, valid: false },
    ],
  };
}

