export async function buildPairing() {
  const phone = id("phone");
  const desktop = id("desktop");
  const code = toB64url(seededRandom("pairing/code")(16));
  const qr = { v: 1 as const, device_id: desktop.deviceId, static_public_key: keys("desktop").x25519_public, pairing_code: code };
  const url = encodePairingUrl(qr as never);
  const sessionId = session("pair");
  const ie = eph("pair/initiator");
  const re = eph("pair/responder");
  const hello = { device_id: phone.deviceId, platform: "ios" as const, name: "Wenjing's iPhone", signing_public_key: keys("phone").ed25519_public };
  const init = new PairInitiator({ qr: decodePairingUrl(url)!, me: phone.noise, hello, sessionId, e: ie });
  const m1 = await init.start();
  const resp = new PairResponder({ desktopId: desktop.deviceId, deviceId: phone.deviceId, sessionId, code, me: desktop.noise, e: re });
  await resp.read(m1);
  const welcome = {
    device_id: desktop.deviceId,
    name: "Wenjing's MacBook Pro",
    signing_public_key: keys("desktop").ed25519_public,
    statement: await signLinkStatement(statementBody({ platform: "ios", method: "qr", device: "phone" }), desktop.signing),
  };
  const m2 = await resp.reply(welcome);
  await init.finish(m2);
  const wrong = new PairInitiator({
    qr: { ...decodePairingUrl(url)!, pairing_code: toB64url(seededRandom("pairing/wrong")(16)) },
    me: phone.noise,
    hello,
    sessionId,
    e: eph("pair/wrong"),
  });
  return {
    $comment: COMMENT("QR pairing (§9.6): Noise_IKpsk1, psk = HKDF-SHA256(code; salt = label; info = 'psk:' + desktop id)."),
    devices: { desktop: keys("desktop"), phone: keys("phone") },
    qr,
    url,
    psk: toHex(pairingPsk(code, desktop.deviceId)),
    offer_tag: offerTag(code),
    session_id: sessionId,
    initiator_ephemeral: toHex(ie.secretKey),
    responder_ephemeral: toHex(re.secretKey),
    hello,
    welcome,
    message1: toB64url(m1),
    message2: toB64url(m2),
    reject_message1: [{ name: "made with a different code", data: toB64url(await wrong.start()) }],
    urls: [
      { url, valid: true },
      { url: url.replace("homerun://pair", "homerun://evil"), valid: false },
      { url: "homerun://pair?d=bm90IGpzb24", valid: false },
      { url: `homerun://pair?d=${toB64url(utf8(JSON.stringify({ ...qr, pairing_code: "short" })))}`, valid: false },
    ],
  };
}

// ---------------------------------------------------------------- linking

export async function buildLinking() {
  const phone = id("phone");
  const desktop = id("desktop");
  const sessionId = session("link");
  const nP = seededRandom("link/nP")(32);
  const nD = seededRandom("link/nD")(32);
  const ie = eph("link/initiator");
  const re = eph("link/responder");
  const info = { device_id: phone.deviceId, platform: "ios" as const, name: "Wenjing's iPhone", signing_public_key: keys("phone").ed25519_public };
  const dinfo = { device_id: desktop.deviceId, name: "Wenjing's MacBook Pro", signing_public_key: keys("desktop").ed25519_public };
  const p = new LinkInitiator({ deviceId: phone.deviceId, desktopId: desktop.deviceId, sessionId, me: phone.noise, info, e: ie, nonce: nP });
  const d = new LinkResponder({ deviceId: phone.deviceId, desktopId: desktop.deviceId, sessionId, me: desktop.noise, info: dinfo, e: re, nonce: nD });
  const m1 = await p.start();
  const m2 = await d.accept(m1);
  const m3 = await p.answer(m2);
  const m4 = await d.commit(m3);
  const m5 = p.reveal(m4);
  const code = d.verify(m5);
  if (code !== p.code) throw new Error("codes differ");
  const statement = await signLinkStatement(statementBody({ platform: "ios", method: "code", device: "phone" }), desktop.signing);
  const m6 = d.linked(statement);
  p.result(m6);
  return {
    $comment: COMMENT("Linking with a matching code (§10.5): Noise_XX, then commit/reveal; code = 6 digits of SHA-256(label ‖ handshake hash ‖ nP ‖ nD), first 8 bytes big-endian mod 10^6."),
    devices: { desktop: keys("desktop"), phone: keys("phone") },
    session_id: sessionId,
    initiator_ephemeral: toHex(ie.secretKey),
    responder_ephemeral: toHex(re.secretKey),
    phone_nonce: toHex(nP),
    desktop_nonce: toHex(nD),
    commit: toB64url(sasCommit(nP)),
    code,
    phone_info: info,
    desktop_info: dinfo,
    statement,
    messages: [m1, m2, m3, m4, m5, m6].map(toB64url),
    codes: [
      { handshake_hash: "00".repeat(32), phone_nonce: "11".repeat(32), desktop_nonce: "22".repeat(32), code: sasCode(new Uint8Array(32), new Uint8Array(32).fill(0x11), new Uint8Array(32).fill(0x22)) },
      { handshake_hash: "ff".repeat(32), phone_nonce: "00".repeat(32), desktop_nonce: "00".repeat(32), code: sasCode(new Uint8Array(32).fill(0xff), new Uint8Array(32), new Uint8Array(32)) },
    ],
  };
}

// ---------------------------------------------------------------- APNs

export async function buildApns() {
  const desktop = id("desktop");
  const phone = id("phone");
  const base = {
    v: 1 as const,
    sender_device_id: desktop.deviceId,
    created_at: T0,
    expires_at: T0 + 24 * HOUR,
  };
  const pushOf = (label: string, title: string, body: string) =>
    seal({
      inner: { ...base, msg_id: msgId(`apns/${label}`), body: { type: "push", category: "run_finished", title, body } } as SealedInner,
      to: phone.deviceId,
      sender: desktop.noise,
      recipientStatic: phone.noise.publicKey,
      e: eph(`apns/${label}`),
    });
  const small = await pushOf("small", "Run finished", "Weekly report: done in 3 min.");
  const big = await pushOf("big", "Run finished", "🙂".repeat(1000));
  const cases = [
    { name: "fits", envelope: small },
    { name: "too big for 4 KB: generic text only", envelope: big },
  ].map((c) => ({ ...c, ...buildApnsPayload(c.envelope) }));
  return {
    $comment: COMMENT("APNs payloads (§9.7): at most 4,096 bytes; the sealed envelope rides in `hr` when it fits."),
    max_bytes: 4096,
    cases,
  };
}

